const { chromium } = require('playwright-core');
const path = require('path');
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--no-sandbox','--enable-unsafe-swiftshader','--use-angle=swiftshader','--hide-scrollbars'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errs = [];
  page.on('pageerror', e => errs.push(String(e).slice(0,200)));
  await page.addInitScript(() => { try { localStorage.setItem('zenou_tour_done','true'); } catch(e){} });
  await page.goto('http://127.0.0.1:8000/index.html', { waitUntil: 'networkidle' });
  await page.waitForTimeout(2500);
  console.log('nav:', await page.locator('.mainnav a').allTextContents());
  console.log('count:', await page.locator('#lpCount').textContent());
  const cards = await page.locator('.card, .game-card, [data-id]').count();
  console.log('new entries present:', await page.evaluate(() => ['Zenou City','Clustertruck','Crossy Road','How to Fish'].map(t => document.body.innerText.includes(t))));
  await page.screenshot({ path: path.resolve('../shots/site-home-new.png') });
  await page.goto('http://127.0.0.1:8000/play.html?g=lo-clustertruck', { waitUntil: 'networkidle' });
  await page.waitForTimeout(9000);
  await page.screenshot({ path: path.resolve('../shots/site-play-ct.png') });
  console.log('player title:', await page.title());
  console.log('errors:', errs.slice(0,4).join(' ~ ') || 'none');
  await browser.close();
})();
